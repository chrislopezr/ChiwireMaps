#!/usr/bin/env python3
"""Convert a NOAA World Magnetic Model coefficient file (WMM.COF) into wmm.js for the SD card.

Usage:
    python3 tools/make_wmm_js.py path/to/WMM2025.COF sdCard/wmm.js

Get the COF file from https://www.ncei.noaa.gov/products/world-magnetic-model/wmm-coefficients
(WMM2025 is valid 2025.0-2030.0; replace it with the next model when it is released).
"""
import json
import sys


def main(cof_path, out_path):
    with open(cof_path, encoding="ascii") as f:
        lines = [line.split() for line in f if line.strip()]
    epoch, model, release = float(lines[0][0]), lines[0][1], lines[0][2]
    coefs = []
    for parts in lines[1:]:
        if parts[0].startswith("9999"):
            break
        n, m = int(parts[0]), int(parts[1])
        g, h, gdot, hdot = (float(v) for v in parts[2:6])
        coefs.append([n, m, g, h, gdot, hdot])
    with open(out_path, "w", encoding="ascii") as f:
        f.write(f"// {model} coefficients (epoch {epoch}, released {release}), generated by tools/make_wmm_js.py\n")
        f.write(f"// Source: NOAA NCEI / BGS World Magnetic Model. Valid {epoch:.1f}-{epoch + 5:.1f}.\n")
        f.write("window.WMM_MODEL = " + json.dumps({"name": model, "epoch": epoch, "coefs": coefs},
                                                  separators=(",", ":")) + ";\n")
    print(f"Wrote {len(coefs)} coefficients ({model}, epoch {epoch}) to {out_path}")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2])
