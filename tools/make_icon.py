#!/usr/bin/env python3
"""Draw the Chiwire Maps capybara icon and write every size the project uses.

    python3 tools/make_icon.py            (needs Pillow: pip install pillow)

Writes:
  sdCard/favicon.ico                    browser tab (16, 32, 48 px)
  sdCard/icon-192.png                   phone home screen and the map page panel
  docs/images/chiwire-maps.png          README header (512 px)
  firmware/include/capybara_icon.h      dongle screen at boot (64 x 64, RGB565 on black)
"""
import os

from PIL import Image, ImageDraw

REPO = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
S = 512  # drawing size; everything else is scaled down from it

POND = (126, 186, 140)
FUR = (164, 108, 62)
FUR_DARK = (118, 74, 40)
OUTLINE = (70, 42, 22)
YUZU = (247, 168, 38)
LEAF = (60, 140, 60)


def draw():
    img = Image.new("RGBA", (S, S), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    d.ellipse((8, 8, S - 8, S - 8), fill=POND)
    w = 10
    grow = lambda box: (box[0] - w, box[1] - w, box[2] + w, box[3] + w)
    # Short legs and the ear sit behind the body and head
    for x in (150, 300):
        d.rounded_rectangle((x, 360, x + 50, 440), 22, fill=FUR_DARK, outline=OUTLINE, width=w)
    d.ellipse((300, 112, 352, 164), fill=FUR_DARK, outline=OUTLINE, width=w)
    # Body and head (long, boxy, blunt nose: a brick with ears) as one silhouette: all outlines, then all fills
    body, head = (70, 190, 400, 420), (280, 140, 470, 300)
    d.ellipse(grow(body), fill=OUTLINE)
    d.rounded_rectangle(grow(head), 70 + w, fill=OUTLINE)
    d.ellipse(body, fill=FUR)
    d.rounded_rectangle(head, 70, fill=FUR)
    # Eye and nostril
    d.ellipse((378, 178, 404, 204), fill=OUTLINE)
    d.ellipse((442, 214, 460, 236), fill=OUTLINE)
    # A yuzu on its head, as capybaras in hot springs wear them
    d.ellipse((350, 64, 424, 138), fill=YUZU, outline=OUTLINE, width=w)
    d.polygon([(386, 70), (420, 40), (412, 78)], fill=LEAF, outline=OUTLINE)
    return img


def rgb565_header(img, name):
    small = Image.new("RGB", img.size, (0, 0, 0))
    small.paste(img, mask=img)
    raw = small.tobytes()
    pixels = [((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3) for r, g, b in zip(raw[0::3], raw[1::3], raw[2::3])]
    rows = [", ".join(f"0x{p:04X}" for p in pixels[i:i + 16]) for i in range(0, len(pixels), 16)]
    return (f"// Generated by tools/make_icon.py: the Chiwire Maps capybara, {img.width}x{img.height} RGB565 on black.\n"
            "#pragma once\n#include <pgmspace.h>\n\n"
            f"const uint16_t {name}_width = {img.width}, {name}_height = {img.height};\n"
            f"const uint16_t {name}[] PROGMEM = {{\n" + ",\n".join(rows) + "\n};\n")


def main():
    img = draw()
    path = lambda *p: os.path.join(REPO, *p)
    img.save(path("sdCard", "favicon.ico"), sizes=[(16, 16), (32, 32), (48, 48)])
    img.resize((192, 192), Image.LANCZOS).save(path("sdCard", "icon-192.png"), optimize=True)
    os.makedirs(path("docs", "images"), exist_ok=True)
    img.save(path("docs", "images", "chiwire-maps.png"), optimize=True)
    with open(path("firmware", "include", "capybara_icon.h"), "w") as f:
        f.write(rgb565_header(img.resize((64, 64), Image.LANCZOS), "capybara_icon"))
    print("Icon written: favicon.ico, icon-192.png, docs/images/chiwire-maps.png, capybara_icon.h")


if __name__ == "__main__":
    main()
